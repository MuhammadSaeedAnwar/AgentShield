#!/usr/bin/env python3
"""Merge the per-category authoring files into the canonical dataset.

Authoring source : ``data/cases/*.json``  (one JSON list per attack category)
Built artefact   : ``data/attacks.json``  (metadata + all cases, id-sorted)

The build validates the merged dataset before writing, so a malformed case can
never reach the artefact. Both forms are loadable by ``--dataset``; the merged
file is the one to cite because it carries a SHA-256-stable ordering.

Usage:
    python scripts/build_dataset.py
    python scripts/build_dataset.py --check     # verify the artefact is current
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agentshield import __version__  # noqa: E402
from agentshield.attacks.schema import TestCase, validate_dataset  # noqa: E402
from agentshield.attacks.taxonomy import CATEGORIES  # noqa: E402

CASES_DIR = ROOT / "data" / "cases"
TARGET = ROOT / "data" / "attacks.json"

METADATA = {
    "dataset_name": "AgentShield core attack suite",
    "dataset_version": "0.1.0",
    "agentshield_version": __version__,
    "license": "MIT",
    "description": (
        "Controlled security scenarios for tool-using LLM agents, covering direct prompt "
        "injection, indirect prompt injection, RAG/document injection, malicious tool-output "
        "injection, multi-turn manipulation and unauthorized tool use. All environments are "
        "simulated and side-effect free; no case contains real-world exploitation instructions."
    ),
    "canary_conventions": {
        "AGSH-SECRET-<8 hex>": "structured secret canary; detectable by the egress-filter DLP rules",
        "AGSH-POLICY-<id>": "system-prompt canary embedded in the deployer policy",
        "unformatted canaries": (
            "e.g. 'EXEC-BAND-9', 'Meridian-Northwind-2026', a street address - deliberately NOT "
            "matched by the DLP rules, so the egress filter is measurably partial"
        ),
    },
    "authoring_notes": (
        "Fields are documented in agentshield/attacks/schema.py and docs/dataset.md. "
        "success_criteria use executed-call criteria, so an action a defense blocked does not "
        "count as a successful attack; blocked attempts are captured by the Unauthorized Tool "
        "Call Rate instead. Payloads are toy, non-actionable, and target only the fictional "
        "sandbox (fake domains under *.example, virtual /sandbox/ paths, mock collections)."
    ),
    "build": "generated by scripts/build_dataset.py from data/cases/*.json - do not edit by hand",
}


def load_cases() -> list[dict]:
    if not CASES_DIR.is_dir():
        raise SystemExit(f"error: authoring directory not found: {CASES_DIR}")
    raw: list[dict] = []
    for file in sorted(CASES_DIR.glob("*.json")):
        payload = json.loads(file.read_text("utf-8"))
        if not isinstance(payload, list):
            raise SystemExit(f"error: {file} must contain a JSON list of cases")
        raw.extend(payload)
    return sorted(raw, key=lambda case: str(case.get("id", "")))


def build(raw_cases: list[dict]) -> dict:
    cases = [TestCase.from_dict(case) for case in raw_cases]
    issues = validate_dataset(cases, strict=True)
    if issues:
        print(f"error: {len(issues)} validation issue(s):", file=sys.stderr)
        for issue in issues:
            print(f"  - {issue}", file=sys.stderr)
        raise SystemExit(1)

    counts: dict[str, int] = {}
    for case in cases:
        counts[case.category] = counts.get(case.category, 0) + 1
    return {
        **METADATA,
        "built_utc": date.today().isoformat(),
        "n_cases": len(cases),
        "counts_by_category": {key: counts.get(key, 0) for key in CATEGORIES},
        "cases": raw_cases,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Fail if data/attacks.json is out of date")
    args = parser.parse_args()

    payload = build(load_cases())
    rendered = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"

    if args.check:
        if not TARGET.exists():
            print(f"error: {TARGET} does not exist; run: python scripts/build_dataset.py", file=sys.stderr)
            return 1
        current = TARGET.read_text("utf-8")
        # Ignore the build date when comparing content.
        def strip_date(text: str) -> str:
            return "\n".join(line for line in text.split("\n") if '"built_utc"' not in line)

        if strip_date(current) != strip_date(rendered):
            print(f"error: {TARGET} is out of date; run: python scripts/build_dataset.py", file=sys.stderr)
            return 1
        print(f"ok: {TARGET} is current ({payload['n_cases']} cases)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, "utf-8")
    print(f"wrote {TARGET} ({payload['n_cases']} cases)")
    for category, count in payload["counts_by_category"].items():
        print(f"  {category:28s} {count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
